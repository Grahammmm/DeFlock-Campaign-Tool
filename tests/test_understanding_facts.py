"""Synthetic-only cited fact validation."""
import unittest
from unittest.mock import patch
from campaign_tool.records.understanding import facts
from campaign_tool.records.understanding import evidence


SUBJECT = evidence.sha(b'synthetic original')
RECEIPT = evidence.sha(b'synthetic receipt')
QUOTE = 'Records remain for 30 days.'


def make_bundle(pages, kind='pdf_page'):
    units = [evidence.unit(
        {'kind': kind, 'locator': {'page': i}, 'text': text, 'data': {}},
        SUBJECT, RECEIPT, i) for i, text in enumerate(pages, 1)]
    return evidence.bundle(units, {SUBJECT: {}}, [{
        'original_sha256': SUBJECT, 'receipt_sha256': RECEIPT,
        'attempt_kind': 'native', 'declared_unit_count': len(units),
        'normalized_unit_count': len(units)}])


def candidate(**changes):
    return dict(dict(original_sha256=SUBJECT, category='retention', claim=QUOTE,
                     value=None, quote=QUOTE, page=1), **changes)


class FactsTests(unittest.TestCase):
    def test_supported_citation(self):
        bundle = make_bundle(['É 😀 prefix. ' + QUOTE])
        result = facts.validate(bundle, [candidate()])
        self.assertEqual(result['counts']['verified'], 1)
        fact = result['verified'][0]
        self.assertEqual(fact['status'], 'review_required')
        self.assertFalse(result['accepted'])
        support = fact['citations'][0]
        self.assertEqual(support['quote'], QUOTE)
        self.assertEqual(support['span']['start_byte'], len('É 😀 prefix. '.encode()))
        evidence.validate_citation(support, bundle)


