class ParityTests(unittest.TestCase):
    def test_snapshot_parity(self):
        for name, pages, fields, expected in PARITY:
            with self.subTest(name=name):
                bundle = make_bundle(pages)
                f = dict(fields, original_sha256=SUBJECT)
                # A non-string quote is rejected by the public API's stronger shape gate;
                # retain the verbatim snapshot helper's no_quote result too.
                if fields['quote'] is None:
                    result, reason = facts.check_fact(fields, SUBJECT, {}, '')
                    self.assertIsNone(result)
                    self.assertEqual(reason, expected)
                    continue
                result = facts.validate(bundle, [f])
                if expected:
                    self.assertEqual(result['dropped'], [{'index': 0, 'reason': expected}])
                    self.assertEqual(result['verified'], [])
                    self.assertEqual(result['counts']['by_reason'], {expected: 1})
                else:
                    self.assertEqual(result['dropped'], [])
                    fact = result['verified'][0]
                    support = fact['citations'][0]
                    evidence.validate_citation(support, bundle)
                    u = next(u for u in bundle['units'] if u['unit_id'] == support['unit_id'])
                    span = support['span']
                    self.assertEqual(support['quote'], u['text'].encode()[
                        span['start_byte']:span['end_byte']].decode())
                    if name in ('relocated', 'missing page relocates'):
                        self.assertEqual(fact['page_relocated_from'], fields['page'])
                        self.assertEqual(fact['page'], 2 if name == 'relocated' else 1)
                    self.assertEqual(fact['status'], 'review_required')
                    self.assertFalse(result['accepted'])

    def test_citation_defensive_reasons(self):
        # These branches are unreachable from check_fact's self-generated spans.
        for expected, citation in CITATION_CHECKS:
            with self.subTest(reason=expected):
                self.assertEqual(facts.verify_citation(
                    QUOTE, [(1, 0, len(QUOTE))], citation), expected)

    def test_non_strict_only_skips_support_checks(self):
        bundle = make_bundle([QUOTE])
        f = candidate(claim='Records remain for 60 days.')
        self.assertEqual(facts.validate(bundle, [f])['dropped'][0]['reason'],
                         'claim_value_not_in_quote')
        self.assertEqual(len(facts.validate(bundle, [f], strict=False)['verified']), 1)
        f['claim'] = 'Records retention is unlawful.'
        self.assertEqual(facts.validate(bundle, [f], strict=False)['dropped'][0]['reason'],
                         'legal_conclusion_wording')

    def test_text_lines_and_nonsearchable_units(self):
        for kind, pages, quote, reason in [
            ('text_line', ['Records remain', 'for 30 days.'], QUOTE,
             'quote_spans_units'),
            ('table_row', [QUOTE], QUOTE, 'quote_not_found'),
        ]:
            with self.subTest(kind=kind):
                result = facts.validate(make_bundle(pages, kind), [candidate(quote=quote)])
                self.assertEqual(result['dropped'], [{'index': 0, 'reason': reason}])
        bundle = make_bundle(['É prefix.', QUOTE], 'text_line')
        result = facts.validate(bundle, [candidate(page=17)])
        fact = result['verified'][0]
        self.assertEqual(fact['page'], 1)
        self.assertEqual(fact['page_relocated_from'], 17)
        self.assertEqual(fact['citations'][0]['span']['start_byte'], 0)
        evidence.validate_citation(fact['citations'][0], bundle)

    def test_unknown_document_and_empty_candidates(self):
        bundle = make_bundle([QUOTE])
        result = facts.validate(bundle, [candidate(original_sha256=evidence.sha(b'unknown'))])
        self.assertEqual(result['dropped'], [{'index': 0, 'reason': 'unknown_document'}])
        self.assertEqual(facts.validate(bundle, [])['counts'],
                         {'candidates': 0, 'verified': 0, 'by_reason': {}})

    def test_allowed_words(self):
        f = candidate(claim='Syntheticborough records remain for 30 days.')
        bundle = make_bundle([QUOTE])
        self.assertEqual(facts.validate(bundle, [f])['dropped'][0]['reason'],
                         'claim_terms_not_in_quote')
        self.assertEqual(len(facts.validate(bundle, [f], allowed={'syntheticborough'})['verified']), 1)

    def test_fail_closed(self):
        bundle = make_bundle([QUOTE])
        malformed = [None, {}, [None], [dict(candidate(), extra='no')],
                     [{k: v for k, v in candidate().items() if k != 'value'}]]
        for field in ('original_sha256', 'category', 'claim', 'quote'):
            for wrong in (None, 1, [], {}):
                malformed.append([dict(candidate(), **{field: wrong})])
        for field, wrong in [('value', 1), ('page', '1'), ('page', True),
                             ('claim', '\ud800'), ('value', {})]:
            malformed.append([dict(candidate(), **{field: wrong})])
        for bad in malformed:
            with self.subTest(value=bad):
                with self.assertRaises(facts.FactsError) as ctx:
                    facts.validate(bundle, bad)
                self.assertIn(ctx.exception.code, ('candidate_list', 'candidate_shape', 'candidate_fields'))
                self.assertEqual(str(ctx.exception), ctx.exception.code)
        with self.assertRaisesRegex(facts.FactsError, '^candidate_limit$'):
            facts.validate(bundle, [candidate()] * 2001)
        for bad in (None, {}, dict(bundle, snapshot_sha256=evidence.sha(b'wrong'))):
            with self.assertRaisesRegex(facts.FactsError, '^invalid_bundle$'):
                facts.validate(bad, [candidate()])
        for field, value in [('strict', 1), ('allowed', 'syntheticborough')]:
            with self.assertRaisesRegex(facts.FactsError, '^invalid_options$'):
                facts.validate(bundle, [candidate()], **{field: value})
        # A valid first entry must not yield partial output before a later shape failure.
        with self.assertRaises(facts.FactsError):
            facts.validate(bundle, [candidate(), dict(candidate(), extra=True)])
        self.assertEqual(facts.validate(bundle, [candidate()] * 2000)['counts']['verified'], 2000)

    def test_determinism_isolation_and_input_immutability(self):
        bundle = make_bundle(['É 😀 prefix. ' + QUOTE])
        candidates = [candidate(), candidate(category='unknown'), candidate(claim='Added encryption.')]
        before = evidence.canonical([bundle, candidates])
        with patch('builtins.open', side_effect=AssertionError('I/O')), \
             patch('socket.socket', side_effect=AssertionError('network')), \
             patch('subprocess.Popen', side_effect=AssertionError('process')):
            first = facts.validate(bundle, candidates)
            second = facts.validate(bundle, candidates)
        self.assertEqual(evidence.canonical(first), evidence.canonical(second))
        self.assertEqual(before, evidence.canonical([bundle, candidates]))
        self.assertEqual(first['schema'], 'records-understanding-facts-v1')
        self.assertEqual(first['counts'], {'candidates': 3, 'verified': 1, 'by_reason': {
            'unknown_category': 1, 'claim_terms_not_in_quote': 1}})
        self.assertTrue(first['review_required'])
        self.assertFalse(first['accepted'])

    def test_original_scope_ordinal_order_and_pdf_page_number(self):
        bundle = make_bundle([QUOTE, 'An unrelated synthetic page.'])
        other = evidence.sha(b'other synthetic original')
        other_receipt = evidence.sha(b'other synthetic receipt')
        unit = evidence.unit({'kind': 'pdf_page', 'locator': {'page': 9},
                              'text': QUOTE, 'data': {}}, other, other_receipt, 1)
        bundle = evidence.bundle(bundle['units'] + [unit], {SUBJECT: {}, other: {}},
            bundle['source_receipts'] + [{'original_sha256': other,
                'receipt_sha256': other_receipt, 'attempt_kind': 'native',
                'declared_unit_count': 1, 'normalized_unit_count': 1}])
        result = facts.validate(bundle, [candidate(original_sha256=other, page=9)])
        fact = result['verified'][0]
        self.assertEqual(fact['page'], 9)
        self.assertNotIn('page_relocated_from', fact)
        self.assertEqual(fact['citations'][0]['original_sha256'], other)
        evidence.validate_citation(fact['citations'][0], bundle)
        f = candidate(original_sha256=other, quote='An unrelated synthetic page.')
        self.assertEqual(facts.validate(bundle, [f])['dropped'][0]['reason'], 'quote_not_found')
        bundle = make_bundle(['Records remain', 'for 30 days.'], 'text_line')
        bundle['units'].reverse()
        bundle['snapshot_sha256'] = evidence.sha({k: v for k, v in bundle.items()
                                                 if k != 'snapshot_sha256'})
        self.assertEqual(facts.validate(bundle, [candidate()])['dropped'][0]['reason'],
                         'quote_spans_units')

    def test_repeated_physical_page_preserves_selected_receipt(self):
        receipts = sorted([RECEIPT, evidence.sha(b'second synthetic receipt')])
        for texts in ([f'É 😀 prefix. {QUOTE}', 'A different synthetic page.'],
                      ['A different synthetic page.', f'É 😀 prefix. {QUOTE}'],
                      [QUOTE, QUOTE]):
            units = [evidence.unit({'kind': 'pdf_page', 'locator': {'page': 1},
                                    'text': text, 'data': {}}, SUBJECT, receipt, 1)
                     for text, receipt in zip(texts, receipts)]
            bundle = evidence.bundle(units, {SUBJECT: {}}, [
                {'original_sha256': SUBJECT, 'receipt_sha256': receipt,
                 'attempt_kind': 'native', 'declared_unit_count': 1,
                 'normalized_unit_count': 1} for receipt in receipts])
            for page in (1, None, 99):
                with self.subTest(texts=texts, page=page):
                    result = facts.validate(bundle, [candidate(page=page)])
                    if texts == [QUOTE, QUOTE]:
                        self.assertEqual(result['dropped'], [
                            {'index': 0, 'reason': 'quote_ambiguous_page'}])
                        continue
                    self.assertEqual(result['dropped'], [])
                    fact = result['verified'][0]
                    self.assertEqual(fact['page'], 1)
                    if page == 1:
                        self.assertNotIn('page_relocated_from', fact)
                    else:
                        self.assertEqual(fact['page_relocated_from'], page)
                    support = fact['citations'][0]
                    selected = next(u for u in units if QUOTE in u['text'])
                    self.assertEqual(support['unit_id'], selected['unit_id'])
                    self.assertEqual(support['quote'], QUOTE)
                    self.assertEqual(support['span']['start_byte'], len('É 😀 prefix. '.encode()))
                    evidence.validate_citation(support, bundle)

    def test_supplied_page_disambiguates_repeated_quote(self):
        bundle = make_bundle([QUOTE, QUOTE])
        for page in (1, 2):
            result = facts.validate(bundle, [candidate(page=page)])
            fact = result['verified'][0]
            self.assertEqual(fact['page'], page)
            self.assertNotIn('page_relocated_from', fact)
            self.assertEqual(fact['citations'][0]['unit_id'], bundle['units'][page - 1]['unit_id'])
            evidence.validate_citation(fact['citations'][0], bundle)

    def test_claim_and_value_bounds(self):
        f = candidate(claim=QUOTE + ' ' * 1100 + QUOTE, value=' ' + '30 ' * 80)
        fact = facts.validate(make_bundle([QUOTE]), [f])['verified'][0]
        self.assertEqual(len(fact['claim']), 1000)
        self.assertEqual(len(fact['value']), 120)
