"""Independent synthetic regression tests for the mail-history adoption command.

``records adopt-mail`` (``campaign_tool.records.mail_adoption``) enrolls frozen
mail-history export receipts into the canonical records ledger. These tests are a
second, independent regression suite written against the documented command
interface (module function ``adopt`` plus the ``records adopt-mail`` CLI entry).
They share no fixture code or assertions with the implementation worker's
``test_mail_adoption.py``; the only shared surface is the engine's public
adapters (``mail_delta``, ``eml_export``, ``CanonicalMailBackend`` via the
command) and the synthetic legacy export shape those adapters already define.

Everything here is synthetic: no live mailbox, no private records, no
credentials, no network. The 154-message / 82-attachment fixture is built from
generated bytes and exists only to exercise exact counting at the acceptance
scale; it is NOT the real TEST acceptance run, which a separate local-only
acceptance worker performs against the frozen data copy.
"""
import hashlib
import io
import json
import os
from pathlib import Path
import sqlite3
import sys
import tempfile
import unittest

from contextlib import redirect_stdout
from email.message import EmailMessage
from email.policy import SMTP
from unittest import mock

from campaign_tool.records import mail_adoption
from campaign_tool.records.intake import eml_export, mail_delta
from campaign_tool.records.run import Pipeline


def _blob(mail_root, data):
    """Write synthetic bytes into a content-addressed object and return its descriptor."""
    sha = hashlib.sha256(data).hexdigest()
    rel = Path("objects") / sha[:2] / sha
    eml_export._ensure_private(mail_root / rel, data)
    return {"path": str(rel), "sha256": sha, "bytes": len(data)}


def synthetic_receipt(mail_root, *, uid, validity=900, attachments=0, body=None):
    """Build one legacy-shape synthetic export receipt with a chosen attachment count.

    Returns ``(receipt_path, receipt)``. The receipt is written under
    ``<mail_root>/receipts`` and its EML/attachment bytes under
    ``<mail_root>/objects``, mirroring the frozen export layout the command reads.
    """
    msg = EmailMessage()
    msg["From"] = "records@adopt.example.invalid"
    msg["To"] = "organizer@campaign.example.invalid"
    msg["Subject"] = "Synthetic adoption fixture %d" % uid
    msg["Message-ID"] = "<adopt-fixture-%d@adopt.example.invalid>" % uid
    msg.set_content(body or ("Synthetic adoption body for uid %d.\n" % uid))
    for n in range(attachments):
        payload = ("%%PDF-1.4\nSynthetic attachment %d for uid %d\n%%%%EOF\n" % (n, uid)).encode()
        msg.add_attachment(payload, maintype="application", subtype="pdf",
                           filename="attachment-%d.pdf" % n)
    for index, part in enumerate(msg.walk()):
        if part.is_multipart():
            part.set_boundary("synthetic-adopt-%d-boundary-%d" % (uid, index))
    raw = msg.as_bytes(policy=SMTP)
    attached = []
    for index, part in enumerate(msg.walk()):
        if part.get_filename():
            item = _blob(mail_root, part.get_payload(decode=True))
            item.update(part=index, filename=mail_delta.safe_filename(part.get_filename()),
                        original_filename=part.get_filename(),
                        content_type=part.get_content_type())
            attached.append(item)
    receipt = {"complete": True, "account_id": "synthetic-adopt-account", "folder": "Adoption",
               "uidvalidity": validity, "uid": uid, "bytes": len(raw),
               "internaldate": "2026-01-02T03:04:05Z",
               "original_eml": _blob(mail_root, raw), "attachments": attached}
    key = hashlib.sha256(json.dumps(
        [receipt[k] for k in ("account_id", "folder", "uidvalidity", "uid")]).encode()).hexdigest()
    path = mail_root / "receipts" / (key + ".json")
    eml_export._ensure_private(path, (json.dumps(receipt, sort_keys=True) + "\n").encode())
    return path, receipt


def _write_private(path, data):
    path = Path(path)
    fd = os.open(path, os.O_CREAT | os.O_WRONLY | os.O_TRUNC, 0o600)
    try:
        with os.fdopen(fd, "wb") as stream:
            stream.write(data)
    finally:
        os.chmod(path, 0o600)


def _snapshot(root):
    """Map every file's relative path under ``root`` to its sha256 (read-only probe)."""
    result = {}
    for base, _dirs, files in os.walk(root):
        for name in files:
            path = Path(base) / name
            result[str(path.relative_to(root))] = hashlib.sha256(path.read_bytes()).hexdigest()
    return result


class MailAdoptionRegressionTests(unittest.TestCase):
    """Synthetic regression coverage for configuration-gated, idempotent adoption."""

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.base = Path(self.tmp.name).resolve()
        self.root = Pipeline(self.base / "processing").root.path
        self.export = self.base / "mail-history"
        self.export.mkdir(mode=0o700)
        # Small deterministic fixture: 3 messages, 4 attachments.
        self.receipts = []
        for uid, attachments in ((11, 1), (12, 1), (13, 2)):
            self.receipts.append(synthetic_receipt(self.export, uid=uid, attachments=attachments))

    # -- helpers -------------------------------------------------------------
    def config(self, adoption="enabled", marker_sha=None):
        path = self.base / "adoption-config.json"
        _write_private(path, json.dumps({
            "schema": mail_adoption.CONFIG_SCHEMA, "source": "mail-history",
            "adoption": adoption, "disable_marker_sha256": marker_sha}).encode())
        return path

    def marker(self):
        data = b'{"action":"disable_new_adoption","schema":"synthetic-regression"}\n'
        _write_private(self.root / mail_adoption.DISABLE_MARKER, data)
        return hashlib.sha256(data).hexdigest()

    def count(self, sql):
        con = sqlite3.connect((self.root / "ledger.sqlite").as_uri() + "?mode=ro", uri=True)
        try:
            return con.execute(sql).fetchone()[0]
        finally:
            con.close()

    def adopt(self, **kw):
        return mail_adoption.adopt(self.root, self.export, **kw)

    # -- coverage: configuration-gated adoption ------------------------------
    def test_configuration_gate_refuses_apply_without_enabled_config(self):
        # No config and an explicitly disabled config both close the gate.
        with self.assertRaisesRegex(mail_adoption.AdoptionError, "disabled_no_config"):
            self.adopt(apply=True)
        with self.assertRaisesRegex(mail_adoption.AdoptionError, "disabled_by_config"):
            self.adopt(apply=True, config_path=self.config("disabled"))
        # Nothing reached the ledger.
        self.assertEqual(self.count("SELECT count(*) FROM mail_messages"), 0)
        self.assertEqual(self.count("SELECT count(*) FROM runs WHERE run_id LIKE 'mail-history-%'"), 0)

    def test_disable_marker_is_honoured_and_never_deleted(self):
        sha = self.marker()
        # An enabled config that does not pin the marker cannot adopt.
        with self.assertRaisesRegex(mail_adoption.AdoptionError, "disabled_by_marker"):
            self.adopt(apply=True, config_path=self.config())
        # A wrong pin fails the same way.
        with self.assertRaisesRegex(mail_adoption.AdoptionError, "disabled_by_marker"):
            self.adopt(apply=True, config_path=self.config(marker_sha="0" * 64))
        # The correct pin opens the gate; the marker file itself is untouched.
        report = self.adopt(apply=True, config_path=self.config(marker_sha=sha))
        self.assertEqual(report["gate"]["state"], "enabled_marker_superseded_by_config")
        self.assertEqual(report["adopted_messages"], 3)
        self.assertEqual(hashlib.sha256(
            (self.root / mail_adoption.DISABLE_MARKER).read_bytes()).hexdigest(), sha)

    # -- coverage: accurate message/attachment counts ------------------------
    def test_dry_run_reports_exact_counts_and_mutates_nothing(self):
        ledger_before = (self.root / "ledger.sqlite").read_bytes()
        export_before = _snapshot(self.export)
        report = self.adopt()
        self.assertEqual(report["mode"], "dry-run")
        self.assertEqual(report["source"], "mail-history")
        self.assertEqual((report["receipts"], report["attachments"]), (3, 4))
        self.assertEqual((report["pending_messages"], report["pending_attachments"]), (3, 4))
        self.assertEqual(report["already_adopted"], 0)
        # No ledger or source-file mutation from a dry run.
        self.assertEqual(self.count("SELECT count(*) FROM mail_messages"), 0)
        self.assertEqual((self.root / "ledger.sqlite").read_bytes(), ledger_before)
        self.assertEqual(_snapshot(self.export), export_before)

    def test_synthetic_154_messages_82_attachments_counts_exactly(self):
        # Build the acceptance-scale fixture from generated bytes only.
        scale_export = self.base / "mail-history-154"
        scale_export.mkdir(mode=0o700)
        for uid in range(1, 83):     # 82 messages with one attachment each
            synthetic_receipt(scale_export, uid=uid, attachments=1)
        for uid in range(83, 155):   # 72 messages with no attachments
            synthetic_receipt(scale_export, uid=uid, attachments=0)
        report = mail_adoption.adopt(self.root, scale_export)
        self.assertEqual(report["receipts"], 154)
        self.assertEqual(report["attachments"], 82)
        self.assertEqual(report["pending_messages"], 154)
        self.assertEqual(report["pending_attachments"], 82)

    # -- coverage: successful apply, source=mail-history, idempotency --------
    def test_apply_then_repeat_apply_adopts_zero(self):
        config = self.config()
        report = self.adopt(apply=True, config_path=config)
        self.assertEqual(report["source"], "mail-history")
        self.assertEqual((report["adopted_messages"], report["adopted_attachments"]), (3, 4))
        self.assertEqual(report["failures"], {})
        self.assertEqual(self.count("SELECT count(*) FROM mail_messages"), 3)
        self.assertEqual(self.count("SELECT count(*) FROM occurrences WHERE kind='attachment'"), 4)
        # The run is durable and tagged with the mail-history source.
        summary = json.loads(self.count(
            "SELECT summary FROM runs WHERE run_id LIKE 'mail-history-%'"))
        self.assertEqual(summary["runner_summary"]["source"], "mail-history")
        self.assertEqual(summary["runner_outcome"], "completed")
        runs = self.count("SELECT count(*) FROM runs")
        ledger_before = (self.root / "ledger.sqlite").read_bytes()
        # Re-running adopts zero and writes nothing new.
        again = self.adopt(apply=True, config_path=config)
        self.assertEqual((again["adopted_messages"], again["pending_messages"],
                          again["already_adopted"]), (0, 0, 3))
        self.assertEqual(self.count("SELECT count(*) FROM mail_messages"), 3)
        self.assertEqual(self.count("SELECT count(*) FROM runs"), runs)
        self.assertEqual((self.root / "ledger.sqlite").read_bytes(), ledger_before)

    # -- coverage: preservation of source files ------------------------------
    def test_source_files_preserved_byte_for_byte_after_apply(self):
        before = _snapshot(self.export)
        self.adopt(apply=True, config_path=self.config())
        self.assertEqual(_snapshot(self.export), before)
        # The export directory still holds every receipt and object it started with.
        receipt_files = sorted(p.name for p in (self.export / "receipts").iterdir()
                               if p.name.endswith(".json"))
        self.assertEqual(len(receipt_files), 3)
        self.assertTrue(all(p.is_file() for p in (self.export / "receipts").iterdir()))

    # -- coverage: the CLI entry point exercises the same command -------------
    def test_cli_dry_run_prints_json_and_exits_zero(self):
        argv = ["records adopt-mail", "--root", str(self.root),
                "--mail-history", str(self.export)]
        buffer = io.StringIO()
        with mock.patch.object(sys, "argv", argv), redirect_stdout(buffer):
            code = mail_adoption.main()
        self.assertEqual(code, 0)
        report = json.loads(buffer.getvalue())
        self.assertEqual(report["source"], "mail-history")
        self.assertEqual(report["mode"], "dry-run")
        self.assertEqual((report["receipts"], report["attachments"]), (3, 4))
        self.assertEqual(self.count("SELECT count(*) FROM mail_messages"), 0)


if __name__ == "__main__":
    unittest.main()
